const ALL_KNOWN_PRESETS: readonly CaptionPreset[] = [
  ...UNIVERSAL_CAPTION_PRESETS,
  ...Object.values(CHARACTER_CAPTION_PRESETS).flat(),
]

const PRESET_JA_MAP = new Map<string, CaptionPreset>(
  ALL_KNOWN_PRESETS.map((preset) => [preset.ja, preset])
)

const UNIVERSAL_JA_SET = new Set(
  UNIVERSAL_CAPTION_PRESETS.map((preset) => preset.ja)
)

const FUYUKO_PRESET_SET = new Set(
  (CHARACTER_CAPTION_PRESETS[FUYUKO_SPEAKER] || []).map((preset) => preset.ja)
)

export function getCharacterPresets(
  speaker?: string | null
): readonly CaptionPreset[] {
  if (!speaker) return []
  return CHARACTER_CAPTION_PRESETS[speaker] || []
}

export function isUniversalPresetCaption(caption?: string | null): boolean {
  const normalized = (caption || '').trim()
  return !!normalized && UNIVERSAL_JA_SET.has(normalized)
}

export function isFuyukoPresetCaption(caption?: string | null): boolean {
  const normalized = (caption || '').trim()
  return !!normalized && FUYUKO_PRESET_SET.has(normalized)
}

export function detectFuyukoTrigger(
  text?: string | null
): FuyukoTrigger | null {
  const normalized = (text || '').trim()
  if (!normalized) return null
  return (
    FUYUKO_TRIGGERS.find((trigger) => normalized.startsWith(trigger.prefix)) ||
    null
  )
}

export function stripFuyukoPrefix(text: string): string {
  const normalized = text.trim()
  const trigger = detectFuyukoTrigger(normalized)
  if (!trigger) return normalized
  return normalized.slice(trigger.prefix.length).trim()
}

export function findCaptionPreset(
  caption?: string | null
): CaptionPreset | null {
  const normalized = (caption || '').trim()
  if (!normalized) return null
  return PRESET_JA_MAP.get(normalized) || null
}

export function getCaptionZhLabel(caption?: string | null): string {
  const normalized = (caption || '').trim()
  if (!normalized) return ''
  const exact = PRESET_JA_MAP.get(normalized)
  if (exact) return exact.shortZh
  const trigger = detectFuyukoTrigger(normalized)
  return trigger ? trigger.mode : ''
}
